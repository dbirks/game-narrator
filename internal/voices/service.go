// Provider seams. *tts.Client satisfies both design and base; tests use
// scripted fakes so the domain's rules (consent, immutability, cache key) are
// testable without a gateway.
type (
	// DesignClient synthesises audition candidates on the VoiceDesign
	// checkpoint.
	DesignClient interface {
		Design(ctx context.Context, req tts.DesignRequest) (tts.Audio, error)
	}
	// BaseClient synthesises lines on the Base checkpoint, either in a
	// registered voice or with an inline reference (docs/spec/06 fallback).
	BaseClient interface {
		Generate(ctx context.Context, req tts.GenerateRequest) (tts.Audio, error)
		GenerateWithReference(ctx context.Context, req tts.GenerateRequest, refAudio []byte, refText string) (tts.Audio, error)
	}
	// RegistryClient is the per-instance registry the reconciliation passes
	// keep in sync (docs/spec/06 "VoiceRegistryManager").
	RegistryClient interface {
		Ensure(ctx context.Context, required []tts.Voice) (tts.EnsureReport, error)
		List(ctx context.Context) (tts.ListResult, error)
	}
)

// Service is the voice workflow. All collaborators are required: a voice
// endpoint that silently degrades to "no voices" would hide a wiring bug the
// same way an unwired event hub hides one, so a nil collaborator is a
// construction error, not a runtime 503.
type Service struct {
	Store    Store
	Assets   assets.Store
	Design   DesignClient
	Base     BaseClient
	Registry RegistryClient
	Speech   *speech.Cache
	// InstanceID names this provider instance in voice_registrations.
	InstanceID string
	// BaseModelID is the Base checkpoint's model identity for cache keys
	// (docs/spec/07: TTSModelID is the model the gateway routes on — the
	// synthesising model, not the design model that shaped the reference).
	BaseModelID string
	// BackendDigest is the preview's backend_config_digest (ADR-0023): it
	// changes when the synthesis backend configuration changes, which is when
	// cached previews must stop being reusable.
	BackendDigest string
	// Language is the design/preview language code; empty means server default.
	Language string
	// InstructionCap is the ceiling (in runes) the VoiceDesign instruction
	// derived from a brief may reach before it is sent to the design
	// checkpoint (ADR-0050). The live gateway caps the instructions field
	// at 500 characters; <= 0 uses DesignInstructionCap, so a struct-literal
	// Service behaves like one built with defaults.
	InstructionCap int
	// ASR runs the audition QA read-back (FR-10, ADR 0061): each audition
	// clip is transcribed and compared against the line it was synthesised
	// from, and the verdict (WER/CER, transcript, model, request id) is
	// persisted on the audition row. Nil is a supported degraded
	// configuration (the speech_asr role is not configured): the check is
	// simply not run, the UI reports QA as not-run, and neither playback nor
	// approval ever blocks on ASR.
	ASR speech.ASRClient
	// QA runs the generated-line QA on cache insert (ADR 0061): a freshly
	// committed line is read back, and an over-bound transcript regenerates
	// once before the entry is flagged. Nil (the role not configured) means
	// the check simply does not run; the runtime never blocks playback on
	// either check.
	QA *speech.QAEngine
}

// New validates the wiring.
func New(s *Service) error {
	if s == nil {
		return errors.New("voices: New requires a Service")
	}
	if s.Store == nil || s.Assets == nil || s.Design == nil || s.Base == nil ||
		s.Registry == nil || s.Speech == nil {
		return errors.New("voices: Store, Assets, Design, Base, Registry and Speech are all required")
	}
	if s.InstanceID == "" {
		s.InstanceID = DefaultInstanceID
	}
	if s.BackendDigest == "" {
		s.BackendDigest = "preview-v1"
	}
	return nil
}

// CreateDraft opens one design attempt for a character: a new draft revision
// row, with no clips yet. The clips themselves are the slow part — n
// VoiceDesign calls — and in the API they are generated by the durable job
// JobKind (see job.go); the draft exists first so the queued job is
// addressable and the UI can show "designing…" immediately.
func (s *Service) CreateDraft(ctx context.Context, character, brief string, n int) (store.VoiceProfile, error) {
	if strings.TrimSpace(character) == "" {
		return store.VoiceProfile{}, fmt.Errorf("voices: character is empty")
	}
	if strings.TrimSpace(brief) == "" {
		return store.VoiceProfile{}, fmt.Errorf("voices: the voice brief is empty")
	}
	if n < 1 || n > len(SyntheticAuditionLines) {
		return store.VoiceProfile{}, fmt.Errorf("voices: n must be 1..%d, got %d", len(SyntheticAuditionLines), n)
	}

	revision, err := s.Store.NextVoiceRevision(ctx, character)
	if err != nil {
		return store.VoiceProfile{}, fmt.Errorf("voices: next revision for %s: %w", character, err)
	}
	revID := games.NewID()
	now := time.Now().UTC()
	rev := store.VoiceProfile{
		ID: revID, Character: character, Revision: revision,
		State: store.VoiceStateDraft, DesignInstruction: brief,
		Language: s.Language, CreatedAt: now, UpdatedAt: now,
	}
	if err := s.Store.CreateVoiceRevision(ctx, rev); err != nil {
		return store.VoiceProfile{}, fmt.Errorf("voices: create revision: %w", err)
	}
	return rev, nil
}

// CreateAuditions starts one design attempt for a character: a new revision
// row plus N audition clips from the fixed synthetic lines (never game text,
// docs/spec/03). It is the synchronous composition of CreateDraft and
// CreateAuditionsOnDraft — tests and the live workflow use it directly; the
// HTTP API uses the job so a gateway stall never holds a request open.
func (s *Service) CreateAuditions(ctx context.Context, character, brief string, n int) (store.VoiceProfile, []store.VoiceAudition, error) {
	rev, err := s.CreateDraft(ctx, character, brief, n)
	if err != nil {
		return store.VoiceProfile{}, nil, err
	}
	auditions, err := s.fillDraft(ctx, rev, n)
	if err != nil {
		return rev, nil, err
	}
	got, err := s.Store.GetVoiceRevision(ctx, rev.ID)
	if err != nil {
		return store.VoiceProfile{}, nil, err
	}
	return got, auditions, nil
}

// CreateAuditionsOnDraft fills an existing draft revision with audition clips
// (all the synthetic lines: the draft's count was validated at creation and
// the lines are fixed). It is the body of the voice.auditions job, and it is
// idempotent over a crash between AddAuditions and job completion: a draft
// that already has clips is left untouched.
func (s *Service) CreateAuditionsOnDraft(ctx context.Context, profileID string) ([]store.VoiceAudition, error) {
	rev, err := s.Store.GetVoiceRevision(ctx, profileID)
	if err != nil {
		return nil, fmt.Errorf("voices: load draft %s: %w", profileID, err)
	}
	if rev.State != store.VoiceStateDraft {
		return nil, fmt.Errorf("%w: state %s, want %s", ErrInvalidState, rev.State, store.VoiceStateDraft)
	}
	have, err := s.Store.ListAuditions(ctx, profileID)
	if err != nil {
		return nil, err
	}
	if len(have) > 0 {
		return have, nil
	}
	return s.fillDraft(ctx, rev, len(SyntheticAuditionLines))
}

// fillDraft generates and records the audition clips for one draft revision.
// Each clip is validated by the client, committed to the asset store, and
// recorded with its provenance (model, origin, latency, seed). n is capped at
// the number of synthetic lines: more candidates than lines would repeat a
// line and the UI would show the same text twice. The audition rows record
// the FULL brief (Brief: rev.DesignInstruction); only the payload sent to
// the design checkpoint carries the derived, capped instruction — the live
// gateway rejects instructions longer than its 500-character cap (ADR-0050).
func (s *Service) fillDraft(ctx context.Context, rev store.VoiceProfile, n int) ([]store.VoiceAudition, error) {
	instruction := DesignInstruction(rev.DesignInstruction, s.InstructionCap)
	var (
		auditions []store.VoiceAudition
		ids       []string
		now       = time.Now().UTC()
	)
	for i, line := range SyntheticAuditionLines[:n] {
		audio, err := s.Design.Design(ctx, tts.DesignRequest{
			Text: line, Instructions: instruction, Language: s.Language,
		})
		if err != nil {
			return nil, fmt.Errorf("voices: audition %d for %s: %w", i+1, rev.Character, err)
		}
		// The clip's bytes are committed before the row exists: a row without
		// its audio is dead weight, and the asset's SHA-256 is the identity
		// the approval later freezes.
		sha, err := commitAudio(s.Assets, ctx, audio.WAV)
		if err != nil {
			return nil, fmt.Errorf("voices: store audition %d audio: %w", i+1, err)
		}
		a := store.VoiceAudition{
			ID: games.NewID(), VoiceProfileID: rev.ID, Index: i + 1,
			Brief: rev.DesignInstruction, ModelID: audio.Model, SampleText: line,
			Transcript: line, AssetSHA256: sha,
			DurationMS: int64(audio.Duration.Milliseconds()), SampleRate: audio.SampleRate,
			Origin: audio.Origin, RequestID: audio.RequestID,
			LatencyMS: int64(audio.Latency.Milliseconds()), Seed: audio.Seed,
			CreatedAt: now,
		}
		// QA read-back (FR-10, ADR 0061): the clip is transcribed and compared
		// to the line it was synthesised from. The verdict is recorded on the
		// row so the UI can flag it and the approval gate (below) can refuse
		// it. A transcription error is NOT a fail: with the ASR endpoint down
		// the audition is left as "not run", and a voice must remain approvable
		// in the documented degraded mode.
		if s.ASR != nil {
			if tr, err := s.ASR.TranscribeText(ctx, audio.WAV, s.Language); err == nil {
				rec := speech.Evaluate(line, tr.Text)
				a.AsrModel = tr.Model
				a.AsrWER, a.AsrCER = rec.WER, rec.CER
				a.AsrTranscript = tr.Text
				a.AsrRequestID = tr.RequestID
				if rec.Pass {
					a.AsrState = store.VoiceAuditionQAPassed
				} else {
					a.AsrState = store.VoiceAuditionQAFailed
				}
			} else {
				a.AsrState = store.VoiceAuditionQAUnknown
			}
			checked := time.Now().UTC()
			a.AsrCheckedAt = &checked
		}
		auditions = append(auditions, a)
		ids = append(ids, a.ID)
	}
	if err := s.Store.AddAuditions(ctx, rev.ID, ids, auditions); err != nil {
		return nil, fmt.Errorf("voices: record auditions: %w", err)
	}
	return auditions, nil
}

// commitAudio stages and commits one clip, returning its SHA-256.
func commitAudio(assets assets.Store, ctx context.Context, wav []byte) (string, error) {
	staged, _, err := assets.PutStaged(ctx, bytes.NewReader(wav), "")
	if err != nil {
		return "", err
	}
	committed, err := assets.Commit(ctx, staged)
	if err != nil {
		_ = assets.Abort(context.WithoutCancel(ctx), staged)
		return "", err
	}
	return committed.SHA256, nil
}

// Approve freezes one audition of an auditioning revision as its canonical
// reference (docs/spec/07 steps 4-5, ADR-0005): the clip bytes, the exact
// transcript, the design model and the consent record become the row's
// frozen content, the fingerprint is computed, the immutable registry name is
// precomputed, and a pending registration row is opened. consent must be
// meaningful (docs/spec/14) — empty is refused.
func (s *Service) Approve(ctx context.Context, revisionID, auditionID, consent, approver string) (store.VoiceProfile, error) {
	if strings.TrimSpace(consent) == "" {
		return store.VoiceProfile{}, ErrConsentRequired
	}
	rev, err := s.Store.GetVoiceRevision(ctx, revisionID)
	if err != nil {
		return store.VoiceProfile{}, err
	}
	if rev.State != store.VoiceStateAuditioning {
		return store.VoiceProfile{}, fmt.Errorf("%w: state %s, want %s", ErrInvalidState, rev.State, store.VoiceStateAuditioning)
	}
	au, err := s.Store.GetAudition(ctx, auditionID)
	if err != nil {
		return store.VoiceProfile{}, fmt.Errorf("%w: %v", ErrAuditionNotFound, err)
	}
	if au.VoiceProfileID != revisionID {
		return store.VoiceProfile{}, fmt.Errorf("%w: %s belongs to another revision", ErrAuditionNotFound, auditionID)
	}
	// ASR QA gate (FR-10, ADR 0061): an audition whose transcript diverged
	// from the line beyond the bound is flagged, and a flagged audition is
	// not approvable until a human has reviewed the evidence. "Not run"
	// (ASR not configured or the endpoint down) is NOT a gate: the degraded
	// mode keeps the voice approvable and the UI says QA was not run.
	if au.AsrState == store.VoiceAuditionQAFailed {
		return store.VoiceProfile{}, fmt.Errorf("%w: audition %s (wer=%g cer=%g; transcript %q)",
			ErrAuditionFlagged, auditionID, au.AsrWER, au.AsrCER, au.AsrTranscript)
	}

	ref, err := s.loadReference(ctx, au.AssetSHA256)
	if err != nil {
		return store.VoiceProfile{}, err
	}
	// Re-hash the bytes we actually hold: the content address is only as good
	// as the bytes behind it, and approval is the one moment the reference
	// must be provably intact.
	sum := sha256.Sum256(ref)
	refSHA := hex.EncodeToString(sum[:])

	name, err := RegistryName(rev.ID, rev.Character, rev.Revision, ref)
	if err != nil {
		return store.VoiceProfile{}, fmt.Errorf("voices: registry name: %w", err)
	}
	fingerprint := Fingerprint(refSHA, au.Transcript, au.ModelID)

	approved := rev
	approved.State = store.VoiceStateApproved
	approved.ReferenceAssetID = refSHA
	approved.RefTranscript = au.Transcript
	approved.ModelID = au.ModelID
	approved.ConsentProvenance = consent
	approved.ApprovedBy = approver
	now := time.Now().UTC()
	approved.ApprovedAt = &now
	approved.Fingerprint = fingerprint
	approved.UpdatedAt = now
	if err := s.Store.UpdateVoiceProfile(ctx, approved); err != nil {
		return store.VoiceProfile{}, err
	}
	// The pending row records the precomputed name so the UI can show it
	// before the first Register, and so a name collision is visible here, not
	// mid-Ensure.
	if err := s.Store.UpsertVoiceRegistration(ctx, store.VoiceRegistration{
		VoiceProfileID: revisionID, InstanceID: s.InstanceID,
		RegisteredName: name, State: store.VoiceRegPending, LastVerifiedAt: &now,
	}); err != nil {
		return store.VoiceProfile{}, fmt.Errorf("voices: record pending registration: %w", err)
	}
	return s.Store.GetVoiceRevision(ctx, revisionID)
}

// loadReference reads one canonical reference back out of the asset store and
// validates it (docs/spec/05: the WAV is a trust boundary).
func (s *Service) loadReference(ctx context.Context, sha string) ([]byte, error) {
	r, _, err := s.Assets.Get(ctx, sha)
	if err != nil {
		return nil, fmt.Errorf("%w: %s", ErrReferenceMissing, err)
	}
	defer r.Close()
	wav, err := io.ReadAll(r)
	if err != nil {
		return nil, fmt.Errorf("%w: read %s: %v", ErrReferenceMissing, sha, err)
	}
	if _, err := tts.ValidateAudio(wav); err != nil {
		return nil, fmt.Errorf("%w: %s: %v", ErrReferenceMissing, sha, err)
	}
	return wav, nil
}

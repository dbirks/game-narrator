// Generates web/src/api/schema.d.ts from the checked-in OpenAPI contract
// (internal/api/openapi/openapi.json, served at /api/v1/openapi.json).
//
// This lives in its own workspace package because openapi-typescript 7 prints
// TypeScript through the TypeScript 5 compiler API (`ts.factory`), and the
// TypeScript 7 package the app itself compiles against does not expose one —
// requiring it from this directory resolves typescript@5.9.3, nowhere else.
// `pnpm gen:api` runs this file; `pnpm check:api` reruns it into a temp path
// and fails when the committed file has drifted (ADR-0017: the contract is
// authored in Go and contract-tested, so drift here is a bug in one of the two).

import { spawnSync } from "node:child_process";
import { mkdir, readFile, rename, rm, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const webRoot = resolve(here, "..", "..");
const repoRoot = resolve(here, "..", "..", "..");
const source = process.argv[2] ?? resolve(repoRoot, "internal/api/openapi/openapi.json");
const target = process.argv[3]
  ? resolve(process.argv[3])
  : resolve(here, "..", "..", "src/api/schema.d.ts");

const banner = [
  "/* eslint-disable */",
  "// File generated by `pnpm gen:api` from internal/api/openapi/openapi.json.",
  "// Do not edit by hand: `pnpm check:api` fails when this file no longer matches",
  "// the contract. The contract itself is authored in",
  "// internal/api/openapi/openapi.json and kept honest by",
  "// internal/api/openapi_contract_test.go (docs/adr/0017-rest-catalog-api-and-openapi.md).",
  "",
].join("\n");

const schema = await readFile(source, "utf8");
const ast = await openapiTS(JSON.parse(schema));
await mkdir(dirname(target), { recursive: true });
const tmp = `${target}.tmp`;
await writeFile(tmp, banner + astToString(ast));
await rename(tmp, target);
await rm(`${target}.tmp`, { force: true });

// Format the result with the project formatter so `pnpm check:api` output is
// byte-identical to the committed, `pnpm fmt`-clean file (oxfmt is a
// devDependency of the web package, resolved from its node_modules).
const oxfmt = resolve(webRoot, "node_modules", ".bin", "oxfmt");
const fmt = spawnSync(oxfmt, [target], { cwd: webRoot, encoding: "utf8" });
if (fmt.status !== 0) {
  process.stderr.write(fmt.stderr || "oxfmt failed\n");
  process.exit(1);
}

process.stdout.write(`generated ${target}\n`);

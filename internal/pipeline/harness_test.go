// The corpus is the invented 24-frame clip generated by
// scripts/fixtures/gen-synthetic-replay.sh: an empty scene, a textbox appearing, a
// typewriter reveal of one line, that line held, an instant second page, and a
// dismissal. testdata/…/truth.json records the text each frame shows, which is what
// the fake OCR engine below recites — so the fake contributes *recognition*, not a
// single frame of the pipeline's own logic.

const (
	lineA = "The harbour bell rang twice before anyone looked up."
	lineB = "Nobody in the village had seen that boat before."

	msgIDLineA = "synthmsg-harbour"
	msgIDLineB = "synthmsg-boat"
)

func corpusDir(t *testing.T) string {
	t.Helper()
	d := filepath.Join("..", "..", "testdata", "synthetic", "replay", "dialogue-advance-001")
	if _, err := os.Stat(filepath.Join(d, "timestamps.json")); err != nil {
		t.Skipf("NOT RUN: synthetic replay corpus missing (%v); run scripts/fixtures/gen-synthetic-replay.sh", err)
	}
	abs, err := filepath.Abs(d)
	if err != nil {
		t.Fatalf("abs: %v", err)
	}
	return abs
}

type truthRow struct {
	File    string  `json:"file"`
	TsNS    int64   `json:"ts_ns"`
	Present bool    `json:"box_present"`
	Text    string  `json:"text"`
	Full    bool    `json:"text_is_full_line"`
	Line    string  `json:"line"`
	Variant string  `json:"variant"`
	Rect    normBox `json:"rect"`
}

type normBox struct {
	X, Y, W, H float64
}

func readTruth(t *testing.T) []truthRow {
	t.Helper()
	raw, err := os.ReadFile(filepath.Join(corpusDir(t), "truth.json"))
	if err != nil {
		t.Fatalf("truth.json: %v", err)
	}
	var rows []truthRow
	if err := json.Unmarshal(raw, &rows); err != nil {
		t.Fatalf("parse truth.json: %v", err)
	}
	return rows
}

// steps is the preprocessing recipe used by *both* the harness (to key the fake
// engine's script) and the Runner under test (Config.Preprocess). One definition
// is the point: a recipe drift would silently make every fake lookup miss, and the
// test would pass by reading a blank box instead of failing on the drift.
func steps() vision.Steps { return vision.DefaultSteps() }

func decodeFrame(t *testing.T, dir, name string) *image.RGBA {
	t.Helper()
	f, err := os.Open(filepath.Join(dir, name))
	if err != nil {
		t.Fatalf("open %s: %v", name, err)
	}
	defer f.Close()
	img, _, err := image.Decode(f)
	if err != nil {
		t.Fatalf("decode %s: %v", name, err)
	}
	rgba := image.NewRGBA(img.Bounds())
	draw.Draw(rgba, rgba.Bounds(), img, img.Bounds().Min, draw.Src)
	return rgba
}

// ocrScript maps the hash of each frame's preprocessed crop to the text truth.json
// says that frame shows. The key is computed the same way the ROI stage computes
// its dedupe hash — same crop, same recipe, same ImageHash — because that is the
// only identity an ocr.Engine is handed. It also makes the fake answer *which frame
// it was asked about*, rather than which call number it is on, so a pipeline that
// asked about frames out of order would get answers out of order.
func ocrScript(t *testing.T) map[string]string {
	t.Helper()
	dir := corpusDir(t)
	out := map[string]string{}
	for _, r := range readTruth(t) {
		img := decodeFrame(t, dir, r.File)
		crop := vision.CropNormalized(img, vision.Rect{X: r.Rect.X, Y: r.Rect.Y, W: r.Rect.W, H: r.Rect.H}, vision.CropOptions{})
		if crop == nil || crop.Bounds().Empty() {
			t.Fatalf("%s: rect %v crops nothing", r.File, r.Rect)
		}
		out[vision.ImageHash(vision.Preprocess(crop, steps()))] = r.Text
	}
	if len(out) < 10 {
		t.Fatalf("script has only %d distinct crops; the corpus should have one per change", len(out))
	}
	return out
}

// ocrRawScript is the ocrScript of the RAW crop: the hash of the crop's actual
// pixels (the crop as cut, before the recipe greyed, upscaled and thresholded
// it) → the same text. The natural-image secondary the fallback engine runs
// (ocr.RawCropRecognizer, ADR-0040, the 2026-10-18 amendment) reads these pixels, so a scripted VLM
// that simulates "a VLM that reads well" is keyed on THIS map: the recipe's
// output is the primary's identity, the raw crop the secondary's.
func ocrRawScript(t *testing.T) map[string]string {
	t.Helper()
	dir := corpusDir(t)
	out := map[string]string{}
	for _, r := range readTruth(t) {
		img := decodeFrame(t, dir, r.File)
		crop := vision.CropNormalized(img, vision.Rect{X: r.Rect.X, Y: r.Rect.Y, W: r.Rect.W, H: r.Rect.H}, vision.CropOptions{})
		if crop == nil || crop.Bounds().Empty() {
			t.Fatalf("%s: rect %v crops nothing", r.File, r.Rect)
		}
		out[vision.ImageHash(crop)] = r.Text
	}
	if len(out) < 10 {
		t.Fatalf("raw script has only %d distinct crops; the corpus should have one per change", len(out))
	}
	return out
}

func regionRect(t *testing.T) normBox {
	t.Helper()
	rows := readTruth(t)
	return rows[0].Rect
}

// corpusRegion is the ROI the clip was generated against — the textbox minus its
// decorative border, in normalized coordinates (the same rect games.Region stores).
func corpusRegion(t *testing.T) games.Region {
	r := regionRect(t)
	return games.Region{
		ID:         "bottom",
		RegionType: games.RegionTextbox,
		RectX:      r.X,
		RectY:      r.Y,
		RectW:      r.W,
		RectH:      r.H,
	}
}

// index builds the matcher's corpus: the clip's two invented lines, a dozen
// distractors (one sharing page one's prefix, so a ranking on a fragment has to
// abstain rather than guess), and the page1→page2 edge.
func index(t *testing.T) *matcher.Index {
	t.Helper()
	msgs := []games.Message{
		msg(msgIDLineA, lineA),
		msg(msgIDLineB, lineB),
	}
	// Distractors. Invented, as everything here is; the prefix-sharing one exists
	// so that matching a half-revealed line is a real decision rather than a
	// lookup, which is docs/spec/05 "Short strings and overlapping prefixes require
	// more evidence". Deliberately *one* prefix sharer, on page one: a distractor
	// that has page two's line as its own prefix would make page two's read a
	// true prefix of a stored line, and the matcher abstains on exactly that
	// ambiguity ("never invent dialogue to fill uncertainty") — the clip's second
	// line could then never commit, so the distractor diverges instead.
	for i, text := range []string{
		"The harbour bell rang twice before the fog lifted.",
		"The harbour bell was missing from the wreck.",
		"Nobody in the village had mentioned the boat before.",
		"The keeper left the lamp burning all night.",
		"Someone had moved the crates before tide turn.",
		"The waterline was higher than the last chart said.",
		"A rowboat sat untied beneath the broken jetty.",
		"Nobody mentioned the light that went out at dusk.",
		"The harbourmaster kept his ledger in the upper drawer.",
		"Something had been dragged across the slipway.",
		"The tide would not turn for another hour.",
		"Every window on the quay faced the same direction.",
	} {
		msgs = append(msgs, msg(distractorID(i), text))
	}
	edges := []games.MessageEdge{{
		FromID:     msgIDLineA,
		ToID:       msgIDLineB,
		EdgeType:   games.EdgeNext,
		Confidence: 0.9,
	}}
	idx, err := matcher.Build(msgs, edges, matcher.IndexOptions{})
	if err != nil {
		t.Fatalf("matcher.Build: %v", err)
	}
	return idx
}

func distractorID(i int) string { return "synthmsg-x" + string(rune('a'+i%26)) + itoa(i/26) }

func itoa(n int) string {
	if n == 0 {
		return "0"
	}
	var b []byte
	for n > 0 {
		b = append([]byte{byte('0' + n%10)}, b...)
		n /= 10
	}
	return string(b)
}

func msg(id, text string) games.Message {
	return games.Message{ID: id, ProfileID: "synth-profile", OriginalText: text, SpeechText: text, TextKind: games.TextDialogue}
}

// fakeOCR is a scripted ocr.Engine. It reads the crop it is handed (by hash) and
// returns the recorded text after a scripted delay.
//
// The delay schedule is what makes the out-of-order test mean something: long reads
// on a half-revealed line, short reads once a line is complete. That is the shape of
// real OCR behaviour — a full line is one pass, a stream of prefixes is a stream of
// calls — reproduced here with the timing dialled up so the supersession paths in
// the ROI stage fire on every run rather than on the unlucky one.
//
// When respectCtx is false the engine ignores cancellation and answers anyway. That
// is a hostile provider, not a well-behaved one, and it is the case
// docs/spec/12's "delayed/duplicated model responses" failure injection names: the
// pipeline must survive an engine that answers after being told not to.
type fakeOCR struct {
	script     map[string]string
	delay      func(text string) time.Duration
	respectCtx bool

	calls    atomic.Int64
	misses   atomic.Int64
	mu       sync.Mutex
	inFlight map[string]int
}

func (f *fakeOCR) Name() string { return "fake" }

func (f *fakeOCR) Recognize(ctx context.Context, img image.Image) (ocr.Result, error) {
	if img == nil || img.Bounds().Empty() {
		return ocr.Result{}, &ocr.Failure{Kind: ocr.ErrFailed, Engine: "fake", Err: context.DeadlineExceeded}
	}
	n := f.calls.Add(1)
	_ = n
	key := vision.ImageHash(img)
	text, ok := f.script[key]
	if !ok {
		f.misses.Add(1)
	}
	if f.delay != nil {
		if d := f.delay(text); d > 0 {
			if f.respectCtx {
				t := time.NewTimer(d)
				defer t.Stop()
				select {
				case <-t.C:
				case <-ctx.Done():
					return ocr.Result{}, &ocr.Failure{Kind: ocr.ErrCancelled, Engine: "fake", Err: ctx.Err()}
				}
			} else {
				// Deliberately not selecting on ctx.Done: see the type comment.
				time.Sleep(d)
			}
		}
	}
	return fakeResult(text), nil
}

// fakeResult is one recognition answer for the recorded text.
//
// The confidence is 0.9375 (15/16), a value that is exactly representable in
// binary float, not 0.94: the tracker's temporal vote weights its entries
// (0.5 + mean word confidence), and for a uniform 0.94 a six-word line and a
// seven-word line average to weights that differ by one ULP (1.44 vs
// 1.4399999999999997). With near-ties the vote's documented "equal evidence →
// the newer frame describes the screen now" rule never fires, and a
// typewriter's accepted text follows ULP noise instead of the latest frame —
// which makes stability claims land on prefixes and page two of the clip
// unreachable. Exact ties are what the tie-break exists for; a real engine's
// per-word confidences are never uniform, so it never hits this degenerate
// case, and the fake recites ground truth, for which a fixed high confidence
// is the honest shape.
func fakeResult(text string) ocr.Result {
	const conf = 0.9375
	res := ocr.Result{Text: text, Engine: "fake", MeanConf: conf}
	if strings.TrimSpace(text) == "" {
		return res
	}
	res.Lines = []ocr.Line{{Text: text, Conf: conf, Box: image.Rect(0, 0, 1000, 100)}}
	x := 0
	for _, w := range strings.Fields(text) {
		width := 20 * len(w)
		res.Words = append(res.Words, ocr.Word{Text: w, Conf: conf, Box: image.Rect(x, 20, x+width, 80)})
		x += width + 20
	}
	return res
}

// harness wires a Runner to the replay source and a hub, and collects what came
// out. It is deliberately a struct of plain parts: every test names the queue
// policy, the speed and the engine it wants, and reads back the same three things.
type harness struct {
	t      *testing.T
	runner *pipeline.Runner
	hub    *events.Hub
	store  *events.MemStore
	src    capture.Source
	eng    *fakeOCR
	cancel context.CancelFunc
	ctx    context.Context
}

func newHarness(t *testing.T, eng ocr.Engine, mut func(*pipeline.Config)) *harness {
	t.Helper()
	idx := index(t)
	cfg := pipeline.Config{
		SessionID:       "synthsession",
		ProfileRevision: "1",
		Regions:         []games.Region{corpusRegion(t)},
		OCR:             eng,
		Index:           idx,
		Preprocess:      steps(),
		Trace:           true,
		Queue:           pipeline.QueueLossless,
		OCRTimeout:      2 * time.Second,
		// The corpus samples at 100 ms per frame, so the tracker is tuned to that
		// cadence rather than the docs/spec/05 defaults, which are sized for a
		// 2–5 Hz OCR loop: the vote window is three frames (the same three-frame
		// majority at 10 Hz that the five-frame default is at 2–5 Hz), and the
		// stability window is one frame interval. Page two of the clip is on
		// screen for exactly four frames; at the default 250 ms window its text
		// would only reach READY on the frame the box is already dismissed, so
		// the clip's second line could never commit no matter how correct the
		// pipeline is. Neither knob is fixture-specific code: both are the
		// tracker's documented settings, chosen here to match the recording's
		// rate.
		Tracker: recognition.Config{
			VoteWindow:   3,
			StableWindow: 100 * time.Millisecond,
		},
	}
	if mut != nil {
		mut(&cfg)
	}
	r, err := pipeline.New(cfg)
	if err != nil {
		t.Fatalf("pipeline.New: %v", err)
	}
	mem := events.NewMemStore()
	hub := events.New(events.WithStore(mem))
	return &harness{t: t, runner: r, hub: hub, store: mem, eng: asFake(eng)}
}

func asFake(e ocr.Engine) *fakeOCR {
	if f, ok := e.(*fakeOCR); ok {
		return f
	}
	return nil
}

func (h *harness) source(speed float64, loop bool) *replay.Source {
	h.src = &replay.Source{Dir: corpusDir(h.t), Speed: speed, Loop: loop}
	return h.src.(*replay.Source)
}

// run drives a replay to completion (or cancellation) and returns the counters,
// the published events and the run error.
func (h *harness) run(t *testing.T, src capture.Source) (pipeline.Stats, []events.Envelope, error) {
	t.Helper()
	ctx, cancel := context.WithCancel(context.Background())
	h.ctx, h.cancel = ctx, cancel
	t.Cleanup(func() {
		cancel()
		if h.src != nil {
			_ = h.src.Close()
		}
		h.hub.Close()
	})
	err := h.runner.Run(ctx, src, h.hub)
	st := h.runner.Stats()
	evs, serr := h.store.After(context.Background(), 0, events.Filter{}, 4096)
	if serr != nil {
		t.Fatalf("read events: %v", serr)
	}
	return st, evs, err
}

// committed extracts (message_id, sequence) pairs from message.committed payloads,
// oldest first — the assertion most of these tests make.
func committed(t *testing.T, evs []events.Envelope) []string {
	t.Helper()
	var out []string
	for _, e := range evs {
		if e.Name != events.MessageCommitted {
			continue
		}
		var d struct {
			MessageID string `json:"message_id"`
			Reason    string `json:"reason"`
		}
		if err := json.Unmarshal(e.Data, &d); err != nil {
			t.Fatalf("message.committed payload: %v", err)
		}
		out = append(out, d.MessageID)
	}
	return out
}

func names(evs []events.Envelope) []string {
	out := make([]string, 0, len(evs))
	for _, e := range evs {
		out = append(out, e.Name)
	}
	return out
}

// lateScript answers a completed line quickly and an unfinished one slowly, so
// supersession and stale-result drops happen on every run.
//
// The slow read deliberately exceeds the corpus's 100 ms frame interval: only a
// read that outlives its frame is superseded by the next one, which is the shape
// of real typewriter OCR — a full line is one pass, a stream of prefixes is a
// stream of cancelled calls — reproduced here with the timing dialled up so the
// supersession paths in the ROI stage fire on every run rather than on the
// unlucky one.
func lateScript(text string) time.Duration {
	switch text {
	case "":
		return 15 * time.Millisecond
	case lineA, lineB:
		return 5 * time.Millisecond
	default:
		return 150 * time.Millisecond
	}
}

// fastScript is the same script without the hostility: everything answers at once.
